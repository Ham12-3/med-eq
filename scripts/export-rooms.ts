// pnpm art:rooms
// Writes art/blend/rooms.json for the art track's step A1: every seeded floor, laid out with the same
// lib/map/layout.ts the app's map uses, so the Blender building lines up with the device markers.
//
// Reads the seed builder, not the database: it is pure, so no Docker is needed, and it gives the
// rooms and GLNs that `pnpm db:reset` creates. Coordinates are three.js metres (x along the corridor,
// z across it with north negative, y up). In Blender, Z up: blender (x, y, z) = three (x, -z, y).

import { mkdirSync, writeFileSync } from "node:fs";
import { buildSeedData } from "@/db/seed/build";
import { CORRIDOR_WIDTH, WALL_HEIGHT, layoutFloor } from "@/lib/map/layout";

const data = buildSeedData("2026-10-27");
const mm = (v: number) => Math.round(v * 1000) / 1000;

const floors = data.floors.map((f) => {
  const building = data.buildings.find((b) => b.id === f.buildingId)!;
  const plan = layoutFloor(
    data.rooms
      .filter((r) => r.floorId === f.id)
      .map((r) => ({
        id: r.id ?? r.gln, gln: r.gln, name: r.name, roomType: r.roomType,
        corridorPosition: r.corridorPosition, corridorSide: r.corridorSide,
      })),
  );
  return {
    nodeName: `floor_${building.code}_L${f.level}`,
    building: { code: building.code, name: building.name },
    level: f.level,
    name: f.name,
    corridor: { ...plan.corridor, length: mm(plan.corridor.length) },
    rooms: plan.rooms.map((r) => ({
      gln: r.gln, meshName: r.meshName, name: r.name, roomType: r.roomType,
      corridorSide: r.corridorSide, corridorPosition: r.corridorPosition,
      x: mm(r.x), z: mm(r.z), width: r.width, depth: r.depth,
    })),
  };
});

const out = {
  note: "Generated by scripts/export-rooms.ts from the seed. Do not edit by hand.",
  units: "metres",
  axes: "three.js: x along the corridor, z across (north negative), y up. Blender (x, y, z) = (x, -z, y).",
  corridorWidth: CORRIDOR_WIDTH,
  wallHeight: WALL_HEIGHT,
  floors,
};

mkdirSync("art/blend", { recursive: true });
writeFileSync("art/blend/rooms.json", JSON.stringify(out, null, 2) + "\n");
console.log(`art/blend/rooms.json: ${floors.length} floors, ${floors.reduce((n, f) => n + f.rooms.length, 0)} rooms`);
for (const f of floors) console.log(`  ${f.nodeName}: ${f.rooms.length} rooms, corridor ${f.corridor.length.toFixed(2)} m`);
